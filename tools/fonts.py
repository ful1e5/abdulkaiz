#!/usr/bin/env python3
"""Self-hosts the two web fonts.

Replaces the two render-blocking cross-origin Google Fonts stylesheets. Each of
those cost a DNS lookup, a TLS handshake and a round trip to fonts.googleapis.com
before the CSS even arrived, and the fonts themselves then came from a second
origin. Serving them from the site's own origin removes both connections.

The faces are subset to the characters the site can actually render, so each
file is a few KB rather than Google's full latin cut.

    python3 tools/fonts.py

Then run build.py, which inlines assets/fonts.css into each page.
"""

import io
import json
import os
import re
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FAMILIES = ["Poppins", "DM Sans"]
WEIGHTS = [400, 500, 600, 700]
UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"
)

# Latin + punctuation + the arrows and marks the copy uses. Wide enough that
# ordinary English edits to content/*.json never fall out of the subset.
RANGES = [
    "U+0020-007E",  # ASCII
    "U+00A0-00FF",  # Latin-1 supplement
    "U+0100-017F",  # Latin extended-A
    "U+2010-2027",  # dashes, quotes, ellipsis
    "U+2030-205E",  # general punctuation
    "U+20AC",       # euro
    "U+2122",       # trade mark
    "U+2190-2199",  # arrows (the social row uses →)
    "U+FEFF",
    "U+FFFD",
]


def fetch(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as fh:
        data = fh.read()
    return data if binary else data.decode("utf-8")


def latin_faces():
    """Return [(family, woff2_url, [weights])] for the latin subset only.

    Faces are grouped by URL. Google serves DM Sans as one variable font for
    every weight — the four @font-face blocks all point at the same file — so
    shipping a face per weight produced four byte-identical 13 KB downloads.
    A single face with a weight *range* covers them all instead.
    """
    q = "&".join(
        "family=%s:wght@%s" % (f.replace(" ", "+"), ";".join(map(str, WEIGHTS)))
        for f in FAMILIES
    )
    css = fetch("https://fonts.googleapis.com/css2?%s&display=swap" % q)
    grouped = {}
    for block in css.split("@font-face"):
        # blocks are preceded by a /* subset */ comment
        if "/* latin */" not in block.split("@font-face")[0]:
            continue
        fam = re.search(r"font-family:\s*'([^']+)'", block)
        wgt = re.search(r"font-weight:\s*(\d+)", block)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        if fam and wgt and url:
            grouped.setdefault((fam.group(1), url.group(1)), []).append(int(wgt.group(1)))

    faces = [(f, u, sorted(w)) for (f, u), w in grouped.items()]
    found = sum(len(w) for _, _, w in faces)
    if found != len(FAMILIES) * len(WEIGHTS):
        sys.exit("expected %d latin faces, found %d" % (len(FAMILIES) * len(WEIGHTS), found))
    return faces


def subset(src_bytes, dst, label):
    from fontTools import subset as fts

    tmp = dst + ".src"
    with open(tmp, "wb") as fh:
        fh.write(src_bytes)
    opts = fts.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.desubroutinize = True
    opts.notdef_outline = True
    opts.recalc_bounds = True
    font = fts.load_font(tmp, opts)
    ss = fts.Subsetter(options=opts)
    ss.populate(unicodes=fts.parse_unicodes(",".join(RANGES)))
    ss.subset(font)
    fts.save_font(font, dst, opts)
    os.remove(tmp)
    return os.path.getsize(dst)


def main():
    out_dir = os.path.join(ROOT, "assets", "fonts")
    os.makedirs(out_dir, exist_ok=True)

    faces = latin_faces()
    rules = []
    total_src = total_out = 0

    for family, url, weights in sorted(faces):
        raw = fetch(url, binary=True)
        slug = family.lower().replace(" ", "-")
        if len(weights) > 1:
            name = "%s-var.woff2" % slug
            spec = "%d %d" % (weights[0], weights[-1])
        else:
            name = "%s-%d.woff2" % (slug, weights[0])
            spec = "%d" % weights[0]
        dst = os.path.join(out_dir, name)
        size = subset(raw, dst, name)
        total_src += len(raw)
        total_out += size
        print(
            "  %-22s %6.1f KB -> %5.1f KB   (weights %s)"
            % (name, len(raw) / 1024, size / 1024, spec)
        )
        rules.append(
            "@font-face{font-family:'%s';font-style:normal;font-weight:%s;"
            "font-display:swap;src:url(assets/fonts/%s) format('woff2')}"
            % (family, spec, name)
        )

    css_path = os.path.join(ROOT, "assets", "fonts.css")
    header = (
        "/* Generated by tools/fonts.py — do not edit.\n"
        "   Self-hosted subsets of %s. Re-run the script to regenerate. */\n"
        % ", ".join(FAMILIES)
    )
    with io.open(css_path, "w", encoding="utf-8") as fh:
        fh.write(header + "\n".join(rules) + "\n")

    print(
        "\n%d faces: %.1f KB -> %.1f KB (subset)"
        % (len(faces), total_src / 1024, total_out / 1024)
    )
    print("wrote assets/fonts.css")


if __name__ == "__main__":
    main()
